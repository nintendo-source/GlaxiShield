package dev.glaxiblade.glaxishield;

import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import net.fabricmc.loader.api.FabricLoader;

import javax.imageio.ImageIO;
import java.awt.*;
import java.awt.image.BufferedImage;
import java.io.ByteArrayInputStream;
import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Duration;
import java.util.Base64;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/** Generates a client resource pack. The pack must be enabled once in Minecraft's Resource Packs menu. */
public final class ShieldPackGenerator {
    private static final HttpClient HTTP = HttpClient.newBuilder().connectTimeout(Duration.ofSeconds(12)).build();
    private ShieldPackGenerator() {}

    public static void generate(String ign, String hex) throws Exception {
        String profileJson = get("https://api.mojang.com/users/profiles/minecraft/" + ign);
        JsonObject profile = JsonParser.parseString(profileJson).getAsJsonObject();
        String uuid = profile.get("id").getAsString();
        String sessionJson = get("https://sessionserver.mojang.com/session/minecraft/profile/" + uuid);
        JsonObject session = JsonParser.parseString(sessionJson).getAsJsonObject();
        String encoded = session.getAsJsonArray("properties").get(0).getAsJsonObject().get("value").getAsString();
        String textureJson = new String(Base64.getDecoder().decode(encoded), StandardCharsets.UTF_8);
        Matcher matcher = Pattern.compile("\\\"url\\\"\\s*:\\s*\\\"(https?://[^\\\"]+)\\\"").matcher(textureJson);
        if (!matcher.find()) throw new IllegalStateException("Mojang profile did not contain a skin URL");
        BufferedImage skin = ImageIO.read(URI.create(matcher.group(1)).toURL());
        if (skin == null || skin.getWidth() < 64 || skin.getHeight() < 32) throw new IllegalStateException("Could not decode player skin");

        Path pack = FabricLoader.getInstance().getGameDir().resolve("resourcepacks").resolve("GlaxiShield Generated");
        Path textureDir = pack.resolve("assets/minecraft/textures/entity");
        Files.createDirectories(textureDir);
        BufferedImage shield = createShield(Color.decode(hex), skin);
        ImageIO.write(shield, "PNG", textureDir.resolve("shield_base_nopattern.png").toFile());
        ImageIO.write(shield, "PNG", textureDir.resolve("shield_base.png").toFile());
        String meta = "{\n  \"pack\": {\n    \"min_format\": [84, 0],\n    \"max_format\": [84, 0],\n    \"description\": \"GlaxiShield · " + ign + " · " + hex + "\"\n  }\n}";
        Files.writeString(pack.resolve("pack.mcmeta"), meta);
        Files.writeString(pack.resolve("README.txt"), "Generated by GlaxiShield. Enable this pack in Options > Resource Packs.\nThe pack changes shield textures client-side only.\n");
    }

    private static String get(String url) throws Exception {
        HttpRequest request = HttpRequest.newBuilder(URI.create(url)).timeout(Duration.ofSeconds(20))
                .header("User-Agent", "GlaxiShield/1.0 (Minecraft client mod)").GET().build();
        HttpResponse<String> response = HTTP.send(request, HttpResponse.BodyHandlers.ofString());
        if (response.statusCode() == 204 || response.statusCode() == 404) throw new IllegalStateException("Minecraft username not found");
        if (response.statusCode() < 200 || response.statusCode() >= 300) throw new IllegalStateException("Mojang skin service returned HTTP " + response.statusCode());
        return response.body();
    }

    private static BufferedImage createShield(Color base, BufferedImage skin) {
        BufferedImage out = new BufferedImage(64, 64, BufferedImage.TYPE_INT_ARGB);
        Graphics2D g = out.createGraphics();
        g.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_OFF);
        Polygon shape = new Polygon(new int[]{5, 59, 59, 52, 32, 12, 5}, new int[]{3, 3, 39, 51, 62, 51, 39}, 7);
        g.setColor(new Color(20, 24, 31)); g.fillPolygon(shape);
        Polygon inner = new Polygon(new int[]{8, 56, 56, 50, 32, 14, 8}, new int[]{6, 6, 38, 48, 58, 48, 38}, 7);
        g.setColor(base); g.fillPolygon(inner);
        g.setColor(base.brighter()); g.setStroke(new BasicStroke(2)); g.drawPolygon(inner);
        // Classic 64x64 skin: front face at (8,8), hat overlay at (40,8).
        BufferedImage face = new BufferedImage(8, 8, BufferedImage.TYPE_INT_ARGB);
        Graphics2D fg = face.createGraphics();
        fg.drawImage(skin, 0, 0, 8, 8, 8, 8, 16, 16, null);
        if (skin.getWidth() >= 64 && skin.getHeight() >= 32) fg.drawImage(skin, 0, 0, 8, 8, 40, 8, 48, 16, null);
        fg.dispose();
        g.drawImage(face, 24, 20, 40, 36, null);
        g.setColor(new Color(0, 0, 0, 110)); g.drawRect(23, 19, 17, 17);
        // Decorative rivets.
        g.setColor(new Color(230, 245, 255));
        g.fillRect(10, 10, 2, 2); g.fillRect(52, 10, 2, 2); g.fillRect(31, 51, 2, 2);
        g.dispose();
        return out;
    }
}
